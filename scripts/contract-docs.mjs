import {readFileSync, writeFileSync} from 'node:fs';

// Orbit's published clauses use bold list items; target clauses use headings.
// Both are retained verbatim in CONTRACT.md, the only source of acceptance/status.
const source = readFileSync('CONTRACT.md', 'utf8');
const statusStart = source.indexOf('\n## Status\n');
if (statusStart < 0) throw Error('CONTRACT.md has no status table.');
const definitions = source.slice(0, statusStart);
const markers = [...definitions.matchAll(/^(?:- \*\*|#{3,4} )([A-Z]+(?:-[A-Z]+)?-\d{3})\s+—\s+([^\n]+)/gm)];
const clauses = new Map(markers.map((marker, index) => {
  const text = definitions.slice(marker.index, markers[index + 1]?.index ?? definitions.length);
  const acceptance = text.match(/\*\*Acceptance:\*\*\s*([^\n]+)/)?.[1];
  if (!acceptance) throw Error(`Missing acceptance: ${marker[1]}`);
  return [marker[1], acceptance.trim()];
}));
const rows = source.slice(statusStart).split('\n').filter(line => /^\| `[A-Z]/.test(line)).map(line => {
  const cells = line.split('|').slice(1, -1).map(cell => cell.trim());
  if (cells.length !== 6) throw Error(`Invalid contract status row: ${cells[0]}`);
  const [quotedId, title, scope, status, evidence, gap] = cells;
  return {id: quotedId.replaceAll('`', ''), title, scope, status, evidence, gap};
});
const ids = rows.map(row => row.id);
if (new Set(ids).size !== ids.length || ids.length !== clauses.size) throw Error('Status and acceptance inventories differ.');
for (const row of rows) {
  if (!clauses.has(row.id) || !['done', 'partial', 'missing'].includes(row.status)) throw Error(`Invalid status: ${row.id}`);
}
const counts = Object.fromEntries(['done', 'partial', 'missing'].map(status => [status, rows.filter(row => row.status === status).length]));
const summary = `${rows.length} clauses: ${counts.done} done, ${counts.partial} partial, ${counts.missing} missing.`;
const acceptance = [
  '# Orbit acceptance', '',
  '<!-- Generated by scripts/contract-docs.mjs from CONTRACT.md. Do not edit. -->', '',
  '[CONTRACT.md](CONTRACT.md) is the source of clause text, acceptance and status. Status describes the implemented scope; it is not a claim of a new test execution, live-provider qualification or deployed acceptance.', '', summary, '',
  ...rows.flatMap(row => [
    `## ${row.id} — ${row.title}`, '', `Status: **${row.status}** (${row.scope}).`, '',
    clauses.get(row.id), '', `Evidence: ${row.evidence}`.trimEnd(), '', `Remaining scope: ${row.gap}`.trimEnd(), '',
  ]),
].join('\n');
const claims = [
  '# Orbit claims', '',
  '<!-- Generated by scripts/contract-docs.mjs from CONTRACT.md. Do not edit. -->', '',
  '[CONTRACT.md](../CONTRACT.md#status) owns these judgments and their boundaries. The [acceptance journeys](../ACCEPTANCE.md) are generated from the same source. A done status does not establish live-provider or deployed-product acceptance beyond the evidence named in the contract.', '', summary, '',
  '| Clause | Scope | Status | Evidence | Remaining scope |',
  '| --- | --- | --- | --- | --- |',
  ...rows.map(row => `| ${row.id} — ${row.title} | ${row.scope} | ${row.status} | ${row.evidence} | ${row.gap} |`), '',
].join('\n');
const outputs = new Map([['ACCEPTANCE.md', acceptance], ['docs/CLAIMS.md', claims]]);
const [mode] = process.argv.slice(2);
if (process.argv.length !== 3 || !['write', 'check'].includes(mode)) throw Error('Usage: node scripts/contract-docs.mjs write|check');
for (const [file, text] of outputs) {
  if (mode === 'write') writeFileSync(file, text);
  else if (readFileSync(file, 'utf8') !== text) throw Error(`${file} differs from CONTRACT.md; run node scripts/contract-docs.mjs write.`);
}
console.log(`${mode}: ${summary}`);
